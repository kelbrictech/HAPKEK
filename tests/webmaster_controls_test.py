from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
worker = (ROOT / "worker" / "index.js").read_text()
rms_html = (ROOT / "rms" / "index.html").read_text()
rms_js = (ROOT / "rms" / "rms.js").read_text()
bootstrap = (ROOT / "scripts" / "create_staff_user.mjs").read_text()
webmaster_bootstrap = (ROOT / "scripts" / "provision_webmaster.mjs").read_text()

checks = {
    "Webmaster identity requires exact username and owner role":
        'String(staff?.username || "").toLowerCase() === "webmaster"' in worker
        and 'String(staff?.role || "").toLowerCase() === "owner"' in worker,
    "export endpoint is Webmaster-only":
        'url.pathname === "/api/rms/webmaster/export"' in worker
        and 'if (!isWebmaster(staff)) response = reply({error:"Webmaster access required"},403)' in worker,
    "master reset endpoint is Webmaster-only":
        'url.pathname === "/api/rms/webmaster/master-reset"' in worker
        and 'rmsWebmasterMasterReset(request,env,staff)' in worker,
    "master reset requires exact confirmation phrase":
        'body?.confirmation !== "RESET STAFF ACCESS"' in worker,
    "master reset disables only non-Webmaster accounts":
        "WHERE username <> 'Webmaster' COLLATE NOCASE" in worker
        and "SET active=0,must_change_pin=1,failed_pin_attempts=0,locked_until=0" in worker,
    "master reset preserves current Webmaster session":
        'DELETE FROM hapkek_staff_sessions WHERE token_hash <> ?' in worker,
    "master reset writes an audit event":
        '"webmaster.master_reset"' in worker and '"staff_access"' in worker,
    "recovery token targets Webmaster owner, not Ana":
        "username='Webmaster' COLLATE NOCASE AND role='owner'" in worker
        and 'nickname:"Webmaster"' in worker
        and 'username=\'Ana\' COLLATE NOCASE' not in worker[worker.index('url.pathname === "/api/webmaster/recovery/temporary-pin"'):worker.index('if (url.pathname === "/api/staff/users"')],
    "master reset does not delete operational tables":
        "DELETE FROM hapkek_pos_sales" not in worker
        and "DELETE FROM hapkek_voucher_claims" not in worker
        and "DELETE FROM hapkek_scores" not in worker,
    "export includes game, voucher, POS and audit records":
        all(s in worker for s in (
            "SELECT * FROM hapkek_scores",
            "SELECT * FROM hapkek_voucher_claims",
            "SELECT * FROM hapkek_pos_sales",
            "SELECT * FROM hapkek_pos_sale_items",
            "SELECT id,actor_staff_id,action,entity_type,entity_id,details_json,created_at FROM hapkek_rms_audit_logs"
        )),
    "export excludes PIN hashes and salts":
        "password_hash" not in worker[worker.index("async function rmsWebmasterExport"):worker.index("async function rmsWebmasterMasterReset")]
        and "password_salt" not in worker[worker.index("async function rmsWebmasterExport"):worker.index("async function rmsWebmasterMasterReset")],
    "export excludes authentication sessions":
        "hapkek_staff_sessions" not in worker[worker.index("async function rmsWebmasterExport"):worker.index("async function rmsWebmasterMasterReset")],
    "Webmaster navigation and controls exist":
        'class="nav webmaster-only"' in rms_html
        and 'id="webmaster"' in rms_html
        and 'id="exportCurrentState"' in rms_html
        and 'id="masterResetForm"' in rms_html,
    "UI explains reset scope and preservation":
        "revokes their active sessions" in rms_html
        and "does <strong>not</strong> delete game scores" in rms_html,
    "client only reveals Webmaster controls to Webmaster owner":
        'String(staff.username||"").toLowerCase()==="webmaster"' in rms_js
        and 'String(staff.role||"").toLowerCase()==="owner"' in rms_js,
    "client calls authenticated export and master reset endpoints":
        'api("/api/rms/webmaster/export")' in rms_js
        and 'api("/api/rms/webmaster/master-reset"' in rms_js,
    "Webmaster bootstrap supports a PIN passed through environment":
        "process.env.HAPKEK_BOOTSTRAP_PIN" in bootstrap
        and '!== "webmaster"' in bootstrap
        and "210000" in bootstrap,
    "Anmer remains Ana-issued only":
        'String(username || "").toLowerCase() === "anmer"' in bootstrap
        and "generated by Ana inside the authenticated HAPKEK RMS dashboard" in bootstrap,
    "dedicated Webmaster bootstrap uses PIN only from environment":
        "process.env.HAPKEK_BOOTSTRAP_PIN" in webmaster_bootstrap
        and "210000" in webmaster_bootstrap
        and "HAPKEK_BOOTSTRAP_PIN" in webmaster_bootstrap,
    "dedicated Webmaster bootstrap uses forced PIN change":
        "must_change_pin=1" in webmaster_bootstrap
        and "active=1,role='owner'" in webmaster_bootstrap,
    "dedicated Webmaster bootstrap does not log PIN or write it to file":
        "console.log(pin)" not in webmaster_bootstrap
        and "writeFile" not in webmaster_bootstrap
        and "password_hash" in webmaster_bootstrap,
}

webmaster_bootstrap_route = worker[worker.index('url.pathname === "/api/webmaster/bootstrap"'):worker.index('url.pathname === "/api/webmaster/recovery/temporary-pin"')]
setup_page = (ROOT / "rms" / "webmaster-setup.html").read_text()

checks.update({
    "first-run Webmaster bootstrap is protected by a separate one-time token":
        'env.WEBMASTER_BOOTSTRAP_TOKEN' in webmaster_bootstrap_route
        and 'if(!secret || !supplied || authDiff!==0)' in webmaster_bootstrap_route,
    "first-run bootstrap refuses to overwrite existing initial setup":
        "SELECT id FROM hapkek_staff_users WHERE username='Webmaster' COLLATE NOCASE" in webmaster_bootstrap_route
        and "if(existing) return reply" in webmaster_bootstrap_route,
    "bootstrap parses a standard Bearer authorization header":
        'replace(/^Bearer\\s+/i,"")' in webmaster_bootstrap_route,
    "initial bootstrap activates Webmaster, Ana and Anmer with intended roles":
        all(name in webmaster_bootstrap_route for name in ("'Webmaster'","'Ana'","'Anmer'","'owner'","'admin'","'staff'"))
        and "active=1" in webmaster_bootstrap_route
        and "must_change_pin=1" in webmaster_bootstrap_route,
    "temporary PINs are generated and hashed only inside the Worker":
        "generateTemporaryStaffCredential()" in webmaster_bootstrap_route
        and "crypto.subtle.deriveBits" in worker
        and "iterations:210000" in worker
        and "password_hash" not in setup_page,
    "initial setup batch is atomic and revokes existing seed sessions":
        "env.DB.batch(statements)" in webmaster_bootstrap_route
        and "DELETE FROM hapkek_staff_sessions" in webmaster_bootstrap_route,
    "initial credentials are returned only in a no-store response":
        "temporaryPin:webmasterPin.pin" in webmaster_bootstrap_route
        and '"Cache-Control":"no-store, private"' in webmaster_bootstrap_route,
    "setup page reads token from URL fragment and removes it from browser history":
        'location.hash' in setup_page and 'history.replaceState' in setup_page,
    "setup page posts to the protected API and displays each one-time credential":
        '"/api/webmaster/bootstrap"' in setup_page
        and 'Authorization":"Bearer "+token' in setup_page
        and 'JSON.stringify({})' in setup_page
        and 'id="credentialList"' in setup_page
        and 'id="copyAll"' in setup_page
        and 'history.replaceState' in setup_page,
})

for label, ok in checks.items():
    print(("PASS " if ok else "FAIL ") + label)
if not all(checks.values()):
    raise SystemExit(1)
print(f"Webmaster controls contract: PASS ({len(checks)} checks)")
